defmodule Spectre.Prism.ReqLLMAdaptersTest.Client do
  @moduledoc false

  def generate_text(model, prompt, opts) do
    send(Keyword.fetch!(opts, :test_pid), {:req_llm_generate, model, prompt, opts})

    case Keyword.get(opts, :fake_error) do
      nil ->
        {:ok,
         %{
           id: "req_1",
           model: model.id,
           text: "generated by #{model.provider}",
           usage: %{input_tokens: 4, output_tokens: 3, total_tokens: 7},
           finish_reason: :stop
         }}

      error ->
        {:error, error}
    end
  end

  def embed(model, input, opts) do
    send(Keyword.fetch!(opts, :test_pid), {:req_llm_embed, model, input, opts})
    {:ok, [1, 2, 3]}
  end
end

defmodule Spectre.Prism.ReqLLMAdaptersTest.Serving do
  @moduledoc false

  def batched_run({pid, :generation}, input) do
    send(pid, {:bumblebee_generation, input})

    %{
      results: [
        %{text: "local result", token_summary: %{input: 5, output: 2, padding: 0}}
      ]
    }
  end

  def batched_run({pid, :embedding}, input) do
    send(pid, {:bumblebee_embedding, input})
    %{embedding: [0.25, 0.5, 0.75]}
  end

  def batched_run({pid, {:return, output}}, input) do
    send(pid, {:bumblebee_return, input})
    output
  end

  def batched_run({_pid, :raise}, _input), do: raise("private serving error")
  def batched_run({_pid, :exit}, _input), do: exit(:private_serving_exit)
  def batched_run({_pid, :throw}, _input), do: throw(:private_serving_throw)

  def run({pid, output}, input) do
    send(pid, {:bumblebee_run, input})
    output
  end
end

